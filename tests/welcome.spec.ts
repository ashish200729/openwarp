import { randomUUID } from "node:crypto";
import { expect, test } from "@playwright/test";
import { checkPage, signIn } from "./support";

test("workers accept a private team invite and employers resume company setup", async ({ page, browser, baseURL }) => {
  test.setTimeout(230_000);
  await page.goto("/get-started");
  for (const colorScheme of ["dark", "light"] as const) {
    await page.emulateMedia({ colorScheme, reducedMotion: "reduce" });
    await page.setViewportSize({ width: colorScheme === "dark" ? 320 : 1280, height: 840 });
    await checkPage(page);
  }
  await page.getByRole("link", { name: /Set up my company/ }).click();
  await page.getByRole("button", { name: "Continue as administrator" }).click();
  await expect(page).toHaveURL(/\/login$/);
  await signIn(page, "admin@openwarp.example", process.env.OPENWARP_E2E_ADMIN_PASSWORD!);
  await expect(page.getByRole("heading", { name: "Company setup" })).toBeVisible();
  await checkPage(page);
  const suffix = randomUUID().slice(0, 8);
  const name = `Alex Join${suffix}`;
  const email = `alex.${suffix}@openwarp.example`;
  const team = `Studio${"W".repeat(60)}${suffix}`;
  const withdrawnEmail = `withdrawn.${suffix}@openwarp.example`;
  await page.goto("/workspace/people/import");
  const csv = `first_name,last_name,email,title,team,employment_type,start_date,status\nAlex,Join${suffix},${email},Designer,${team},contractor,2099-01-05,onboarding\n`;
  const withdrawn = `Casey,Join${suffix},${withdrawnEmail},Designer,${team},contractor,2099-01-05,onboarding\n`;
  await page.getByLabel("CSV file").setInputFiles({ name: "join.csv", mimeType: "text/csv", buffer: Buffer.from(csv + withdrawn) });
  await page.getByRole("button", { name: "Check file" }).click();
  await page.getByRole("button", { name: "Import 2 people" }).click();
  await expect(page).toHaveURL(/imported=2/);
  await page.goto("/workspace/settings/access");
  await page.getByLabel("Employee record").last().selectOption({ label: `Casey Join${suffix}` });
  const lifecycleTab = await page.context().newPage();
  await lifecycleTab.goto(`/workspace/people?q=${withdrawnEmail}`);
  await lifecycleTab.getByRole("link", { name: new RegExp(`Casey Join${suffix}`) }).click();
  await lifecycleTab.getByRole("button", { name: "Cancel onboarding and archive" }).click();
  await lifecycleTab.getByRole("button", { name: "Cancel and archive" }).click();
  await expect(lifecycleTab.getByRole("link", { name: "Restart onboarding" })).toBeVisible();
  await lifecycleTab.close();
  await page.getByRole("button", { name: "Create account" }).click();
  await expect(page.getByRole("main").getByRole("alert")).toContainText("Choose a current employee");
  await expect(page.getByRole("listitem").filter({ hasText: withdrawnEmail })).toHaveCount(0);
  await page.getByLabel("Employee record").last().selectOption({ label: name });
  await page.getByRole("button", { name: "Create account" }).click();
  const account = page.getByRole("listitem").filter({ hasText: email });
  await account.locator("summary").click();
  await account.getByRole("button", { name: "Create invitation link" }).click();
  const link = account.getByRole("status").filter({ hasText: "Share privately" }).locator("code");
  const first = (await link.textContent())!;
  const otherAdminTab = await page.context().newPage();
  await otherAdminTab.goto("/workspace/settings/access");
  const staleAccount = otherAdminTab.getByRole("listitem").filter({ hasText: email });
  await staleAccount.locator("summary").click();
  await expect(staleAccount.getByRole("button", { name: "Revoke link" })).toBeVisible();
  await account.getByRole("button", { name: "Replace invitation link" }).click();
  await expect(link).not.toHaveText(first);
  const replacement = (await link.textContent())!;
  await staleAccount.getByRole("button", { name: "Revoke link" }).click();
  await otherAdminTab.getByRole("dialog").getByRole("button", { name: "Revoke link" }).click();
  await expect(staleAccount.getByRole("alert")).toContainText("This invitation changed");
  await otherAdminTab.close();
  await account.getByRole("button", { name: "Revoke link" }).click();
  await page.getByRole("dialog").getByRole("button", { name: "Revoke link" }).click();
  await expect(link).toHaveCount(0);
  const worker = await browser.newContext({ baseURL, viewport: { width: 390, height: 844 }, reducedMotion: "reduce" });
  try {
    const own = await worker.newPage();
    for (const unavailable of [first, replacement]) {
      await own.goto(unavailable);
      await expect(own.getByRole("heading", { name: "This invitation is unavailable" })).toBeVisible();
    }
    await account.getByRole("button", { name: "Create invitation link" }).click();
    const invite = (await link.textContent())!;
    const wrongAccount = await page.context().newPage();
    await wrongAccount.goto(invite);
    await expect(wrongAccount.getByRole("heading", { name: "Switch accounts to join" })).toBeVisible();
    await wrongAccount.close();
    await own.goto("/join");
    await own.getByLabel("Invitation link or code").fill("https://another.example/join?token=example");
    await own.getByRole("button", { name: "Open invitation" }).click();
    await expect(own.getByRole("main").getByRole("alert")).toContainText("another workspace");
    await own.getByLabel("Invitation link or code").fill(invite);
    await own.getByRole("button", { name: "Open invitation" }).click();
    await expect(own.getByText(`You’ve been invited to the ${team} team.`)).toBeVisible();
    await checkPage(own);
    const anotherTab = await worker.newPage();
    await signIn(anotherTab, "viewer@openwarp.example", process.env.OPENWARP_E2E_VIEWER_PASSWORD!);
    await expect(anotherTab.getByRole("heading", { name: "People overview" })).toBeVisible();
    await anotherTab.close();
    const password = randomUUID();
    await own.getByLabel("New password", { exact: true }).fill(password);
    await own.getByLabel("Confirm new password").fill(password);
    await own.getByRole("button", { name: "Accept invitation" }).click();
    await expect(own.getByRole("main").getByRole("alert")).toContainText("different account");
    await own.reload();
    await own.getByRole("button", { name: "Sign out", exact: true }).click();
    await expect(own.getByText(email, { exact: true })).toBeVisible();
    await own.getByLabel("New password", { exact: true }).fill(password);
    await own.getByLabel("Confirm new password").fill(password);
    await own.getByRole("button", { name: "Accept invitation" }).click();
    await expect(own).toHaveURL(/\/login\?saved=password/);
    await signIn(own, email, password);
    await expect(own.getByRole("heading", { name: "Get set up" })).toBeVisible();
    await own.goto("/get-started/employer");
    await expect(own.getByText(/An administrator manages setup/)).toBeVisible();
    await own.goto("/workspace/setup");
    await expect(own.getByRole("heading", { name: "This page is unavailable" })).toBeVisible();
    await own.goto(invite);
    await expect(own.getByRole("heading", { name: "This invitation is unavailable" })).toBeVisible();
  } finally {
    await worker.close();
  }
});
